/**
 * Generates src/i18n/countryNames.{en,fr}.ts from CLDR data shipped with
 * Node's ICU (Intl.DisplayNames), for every country known by libphonenumber.
 *
 * Run: node scripts/generate-country-names.cjs
 */
const fs = require('fs');
const path = require('path');
const { getCountries } = require('libphonenumber-js/max');

const codes = getCountries().slice().sort();
for (const locale of ['en', 'fr']) {
  const dn = new Intl.DisplayNames([locale], { type: 'region' });
  const lines = codes.map((code) => {
    const name = dn.of(code);
    if (!name || name === code)
      throw new Error(`No ${locale} name for ${code}`);
    return `  ${code}: ${JSON.stringify(name)},`;
  });
  const content = `// Generated by scripts/generate-country-names.cjs from CLDR (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit.
import type { CountryCode } from 'libphonenumber-js/core';

export const countryNames${locale.toUpperCase()}: Partial<Record<CountryCode, string>> = {
${lines.join('\n')}
};
`;
  fs.writeFileSync(
    path.join(__dirname, '..', 'src', 'i18n', `countryNames.${locale}.ts`),
    content
  );
  console.log(locale, codes.length);
}
